#!/usr/bin/env python3
"""Generate platform adapters from a persona pack (stdlib only).

The persona files are the nest — the source of truth. Adapters are
disposable: regenerate them whenever the persona changes.

Outputs (into --out dir):
  soul.json                    manifest in the spirit of SoulSpec
  Modelfile                    Ollama model file with the persona as SYSTEM
  openwebui-system-prompt.txt  paste into Open WebUI model system prompt
  sillytavern-note.md          how to use the Character Card with SillyTavern

Usage: make_adapters.py --persona DIR [--card FILE] --out DIR [--name NAME]
"""
import argparse, json, pathlib, sys

def build_prompt(persona_dir):
    parts = []
    for name in ("IDENTITY.md", "SOUL.md", "AGENTS.md", "STEERING.md"):
        p = persona_dir / name
        if p.exists():
            parts.append(f"# {name}\n\n{p.read_text(encoding='utf-8')}")
    return "\n\n---\n\n".join(parts)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--persona", required=True)
    ap.add_argument("--card")
    ap.add_argument("--out", required=True)
    ap.add_argument("--name", default="Purple Rat")
    a = ap.parse_args()
    persona = pathlib.Path(a.persona); out = pathlib.Path(a.out); out.mkdir(parents=True, exist_ok=True)
    prompt = build_prompt(persona)
    if not prompt:
        sys.exit("no persona files found in " + str(persona))
    files = [p.name for p in persona.glob("*.md")]
    manifest = {
        "spec": "soulspec-inspired-manifest v1 (adapter, generated — persona files are the source)",
        "name": a.name,
        "persona_files": files,
        "card": pathlib.Path(a.card).name if a.card else None,
        "adapters": ["Modelfile", "openwebui-system-prompt.txt", "sillytavern-note.md"],
        "note": "Regenerate after any persona change: python3 nest/make_adapters.py --persona persona --out adapters",
    }
    (out / "soul.json").write_text(json.dumps(manifest, indent=2) + "\n")
    modelfile = (
        "# Ollama Modelfile — generated by nest/make_adapters.py. Persona files are the source; regenerate, don't hand-edit.\n"
        "# Choose a base model that fits your machine, e.g.: FROM llama3.1:8b\n"
        "FROM llama3.1:8b\n"
        "PARAMETER temperature 0.8\n"
        'SYSTEM """\n' + prompt.replace('"""', "'''") + '\n"""\n'
    )
    (out / "Modelfile").write_text(modelfile)
    (out / "openwebui-system-prompt.txt").write_text(prompt + "\n")
    note = (
        "# SillyTavern\n\n"
        "1. Import the Character Card V2 JSON from this project's `card/` folder "
        "(Import Character -> select the .json file).\n"
        "2. Point SillyTavern at your model backend (Ollama or an API).\n"
        "3. The card carries the persona; the persona files in `persona/` remain the source of truth — "
        "regenerate the card if they change.\n"
    )
    (out / "sillytavern-note.md").write_text(note)
    print(f"adapters written to {out}: soul.json, Modelfile ({len(modelfile)} bytes), openwebui-system-prompt.txt ({len(prompt)} bytes), sillytavern-note.md")

if __name__ == "__main__":
    main()
